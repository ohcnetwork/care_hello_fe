/**
 * Plugin override for QuickAction.
 *
 * When the incoming `href` is `questionnaire/allergy_intolerance`,
 * renders a "Diagnosis" quick action instead (using `__base` so host
 * styles are preserved). For every other href the original component
 * renders untouched.
 */
export default function QuickActionOverride(
  props: Record<string, unknown> & {
    __base?: React.ComponentType<Record<string, unknown>>;
  },
) {
  const { __base: Base, ...rest } = props;

  if (!Base) {
    return null;
  }

  if (rest.href === "questionnaire/allergy_intolerance") {
    return (
      <Base
        {...rest}
        icon={<DiagnosisIcon className="text-emerald-700" />}
        shortcut={"D"}
        title="Diagnosis"
        href="questionnaire/diagnosis"
      />
    );
  }

  return <Base {...rest} />;
}
